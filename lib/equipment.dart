/// Nome do exercício em português (tradução por frases e palavras).
String exerciseNamePt(String name) {
  var s = name.toLowerCase().trim();
  final keys = _ptPhrases.keys.toList()
    ..sort((a, b) => b.length.compareTo(a.length));
  for (final k in keys) {
    s = s.replaceAll(k, '\u0001${_ptPhrases[k]}\u0002');
  }
  const equipW = {
    'dumbbell', 'barbell', 'cable', 'kettlebell', 'machine', 'band', 'bands',
    'ez-bar', 'smith', 'lever',
  };
  final out = <String>[];
  final tail = <String>[];
  final re = RegExp('\u0001([^\u0002]*)\u0002|([^\\s\u0001\u0002]+)');
  for (final m in re.allMatches(s)) {
    if (m.group(1) != null) {
      out.add(m.group(1)!);
    } else {
      final w = m.group(2)!;
      if (equipW.contains(w)) {
        tail.add(_ptWords[w]!);
      } else {
        out.add(_ptWords[w] ?? w);
      }
    }
  }
  out.addAll(tail.toSet());
  final r = out.where((w) => w.isNotEmpty).join(' ').trim();
  return r.isEmpty ? name : r[0].toUpperCase() + r.substring(1);
}
